function slugify(text) {
  return text
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
}

function renderChapters(list = chapters) {
  chaptersEl.innerHTML = "";
  tocEl.innerHTML = "";

  if (!list.length) {
    chaptersEl.innerHTML = `<p class="empty">No chapters match that search. Try a broader symbol or concept.</p>`;
    return;
  }

  list.forEach((chapter, index) => {
    const originalIndex = chapters.indexOf(chapter);
    const id = slugify(chapter.title);
    const article = document.createElement("section");
    article.className = "chapter is-highlighted";
    article.id = id;
    article.innerHTML = `
      <button class="chapter__header" type="button" aria-expanded="true">
        <span class="chapter__number">${String(originalIndex + 1).padStart(2, "0")}</span>
        <span>
          <span class="chapter__tag">${chapter.tag}</span>
          <h2>${chapter.title}</h2>
        </span>
        <span aria-hidden="true">⌄</span>
      </button>
      <div class="chapter__body">${chapter.body}</div>
    `;
    chaptersEl.append(article);

    const link = document.createElement("a");
    link.href = `#${id}`;
    link.textContent = `${String(originalIndex + 1).padStart(2, "0")} ${chapter.title}`;
    tocEl.append(link);
  });
}

function renderMap() {
  mapEl.innerHTML = chapters.slice(0, 9).map((chapter, index) => `
    <a class="map-card" href="#${slugify(chapter.title)}">
      <span class="map-card__number">${String(index + 1).padStart(2, "0")}</span>
      <span>
        <h3>${chapter.title}</h3>
        <p>${chapter.summary}</p>
      </span>
    </a>
  `).join("");
}

function renderCards() {
  cardsEl.innerHTML = quickCards.map(([title, text]) => `
    <article class="quick-card">
      <h3>${title}</h3>
      <p>${text}</p>
    </article>
  `).join("");
}

function renderPractices() {
  practiceEl.innerHTML = practices.map((practice) => `
    <article class="practice-card">
      <h3>${practice.title}</h3>
      <p>${practice.text}</p>
      <ul>${practice.prompts.map((prompt) => `<li>${prompt}</li>`).join("")}</ul>
    </article>
  `).join("");
}

function applySearch() {
  const query = searchInput.value.trim().toLowerCase();
  const filtered = chapters.filter((chapter) => {
    const haystack = `${chapter.title} ${chapter.tag} ${chapter.summary} ${chapter.body}`.toLowerCase();
    return haystack.includes(query);
  });
  renderChapters(query ? filtered : chapters);
}

function updateProgress() {
  const max = document.documentElement.scrollHeight - window.innerHeight;
  const ratio = max > 0 ? window.scrollY / max : 0;
  progressBar.style.width = `${Math.min(100, Math.max(0, ratio * 100))}%`;
  backToTop.classList.toggle("is-visible", window.scrollY > 700);
}

function syncActiveToc() {
  const chapterEls = [...document.querySelectorAll(".chapter")];
  const links = [...tocEl.querySelectorAll("a")];
  const current = chapterEls.findLast((chapter) => chapter.getBoundingClientRect().top < 180);
  links.forEach((link) => link.classList.toggle("is-active", current && link.hash === `#${current.id}`));
}

document.addEventListener("click", (event) => {
  const header = event.target.closest(".chapter__header");
  if (!header) return;
  const body = header.nextElementSibling;
  const expanded = header.getAttribute("aria-expanded") === "true";
  header.setAttribute("aria-expanded", String(!expanded));
  body.hidden = expanded;
});

document.querySelectorAll(".density").forEach((button) => {
  button.addEventListener("click", () => {
    document.querySelectorAll(".density").forEach((item) => item.classList.remove("is-active"));
    button.classList.add("is-active");
    document.body.classList.remove("density-focus", "density-cards");
    if (button.dataset.density !== "full") {
      document.body.classList.add(`density-${button.dataset.density}`);
    }
  });
});

searchInput.addEventListener("input", applySearch);
window.addEventListener("scroll", () => {
  updateProgress();
  syncActiveToc();
});
backToTop.addEventListener("click", () => window.scrollTo({ top: 0, behavior: "smooth" }));
themeToggle.addEventListener("click", () => {
  const root = document.documentElement;
  root.dataset.theme = root.dataset.theme === "paper" ? "" : "paper";
});

renderMap();
renderCards();
renderPractices();
renderChapters();
updateProgress();
